function Assert-CanonicalUtf8([string]$relativePath) {
    $path = Join-Path $projectRoot $relativePath
    $bytes = [System.IO.File]::ReadAllBytes($path)
    if ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF) {
        $failures.Add("$relativePath contains a UTF-8 BOM")
    }

    try {
        $strictUtf8 = [System.Text.UTF8Encoding]::new($false, $true)
        $text = $strictUtf8.GetString($bytes)
    } catch {
        $failures.Add("$relativePath is not valid UTF-8")
        return
    }

    if ($text.Contains("`r")) {
        $failures.Add("$relativePath does not use canonical LF line endings")
    }
    if (-not $text.EndsWith("`n")) {
        $failures.Add("$relativePath lacks its final LF")
    }
}

function Get-ByteHash([byte[]]$bytes) {
    $sha256 = [System.Security.Cryptography.SHA256]::Create()
    try {
        return [System.BitConverter]::ToString($sha256.ComputeHash($bytes))
    } finally {
        $sha256.Dispose()
    }
}

function Assert-DeterministicBuilder {
    $releasePaths = @('tangentzx-light.css', 'tangentzx-dark.css')
    $originalBytes = @{}
    $originalHashes = @{}

    foreach ($relativePath in $releasePaths) {
        $path = Join-Path $projectRoot $relativePath
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
            $failures.Add("Cannot snapshot missing build output: $relativePath")
            return
        }
        $originalBytes[$relativePath] = [System.IO.File]::ReadAllBytes($path)
        $originalHashes[$relativePath] = Get-ByteHash $originalBytes[$relativePath]
    }

    $buildSucceeded = $false
    $outputsIdentical = $true
    try {
        & (Join-Path $projectRoot 'scripts/build.ps1')
        $buildSucceeded = $true

        foreach ($relativePath in $releasePaths) {
            $path = Join-Path $projectRoot $relativePath
            if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
                $failures.Add("scripts/build.ps1 removed build output: $relativePath")
                $outputsIdentical = $false
                continue
            }
            $rebuiltHash = Get-ByteHash ([System.IO.File]::ReadAllBytes($path))
            if ($rebuiltHash -cne $originalHashes[$relativePath]) {
                $failures.Add("scripts/build.ps1 changed unchanged-source output bytes: $relativePath")
                $outputsIdentical = $false
            }
        }
    } catch {
        $failures.Add("scripts/build.ps1 execution failed: $($_.Exception.Message)")
    } finally {
        foreach ($relativePath in $releasePaths) {
            $path = Join-Path $projectRoot $relativePath
            $currentHash = if (Test-Path -LiteralPath $path -PathType Leaf) {
                Get-ByteHash ([System.IO.File]::ReadAllBytes($path))
            } else {
                $null
            }
            if ($currentHash -cne $originalHashes[$relativePath]) {
                [System.IO.File]::WriteAllBytes($path, $originalBytes[$relativePath])
            }
        }
    }

    if ($buildSucceeded -and $outputsIdentical) {
        Write-Output 'Deterministic build execution passed.'
    }
}

