function Get-CssRuleBlocks([string]$content) {
    $blocks = [System.Collections.Generic.List[object]]::new()
    $stack = [System.Collections.Generic.Stack[object]]::new()
    $segmentStart = 0

    for ($index = 0; $index -lt $content.Length; $index++) {
        if ($content[$index] -eq '{') {
            $stack.Push([pscustomobject]@{
                Selector = $content.Substring($segmentStart, $index - $segmentStart).Trim()
                BodyStart = $index + 1
                Depth = $stack.Count
            })
            $segmentStart = $index + 1
            continue
        }
        if ($content[$index] -eq '}' -and $stack.Count -gt 0) {
            $rule = $stack.Pop()
            $blocks.Add([pscustomobject]@{
                Selector = $rule.Selector
                Body = $content.Substring($rule.BodyStart, $index - $rule.BodyStart)
                Depth = $rule.Depth
            })
            $segmentStart = $index + 1
        }
    }

    return $blocks
}

function Get-GitTrackedFiles([string]$repository, [string]$pattern) {
    $previousErrorActionPreference = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $files = @(git -C $repository ls-files -- $pattern 2>$null)
        $succeeded = $LASTEXITCODE -eq 0
    } finally {
        $ErrorActionPreference = $previousErrorActionPreference
    }
    [pscustomobject]@{
        Succeeded = $succeeded
        Files = $files
    }
}

