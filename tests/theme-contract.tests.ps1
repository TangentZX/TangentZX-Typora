function Get-OutsideFencedMarkdown([string]$content) {
    $outside = [System.Collections.Generic.List[string]]::new()
    $fence = $null
    $fenceCounts = @{ cpp = 0; text = 0; mermaid = 0 }

    foreach ($line in ($content -split "`n", -1)) {
        if ($null -ne $fence) {
            if ($line -match '^```\s*$') {
                $fence = $null
            }
            continue
        }

        if ($line -match '^```(cpp|text|mermaid)\s*$') {
            $fence = $Matches[1]
            $fenceCounts[$fence]++
            continue
        }
        if ($line -match '^```') {
            throw "showcase.md has an unsupported fenced-code opener: $line"
        }
        if ($line -match '^```\s*$') {
            throw 'showcase.md has a fenced-code closer without an opener'
        }
        $outside.Add($line)
    }

    if ($null -ne $fence) {
        throw "showcase.md has an unclosed $fence fence"
    }

    [pscustomobject]@{
        Outside = $outside -join "`n"
        FenceCounts = $fenceCounts
    }
}

