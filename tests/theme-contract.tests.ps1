function Test-HasForbiddenTyporaCodeSelector([string]$content) {
    foreach ($rule in (Get-CssRuleBlocks $content)) {
        $hasVisualDeclaration = $rule.Body -match '(?i)\b(?:font(?:-family)?|padding(?:-[a-z]+)?|border(?:-[a-z]+)?|border-radius|background(?:-[a-z]+)?|box-shadow|overflow(?:-[a-z]+)?|color)\s*:'
        $hasCodeMirrorLineBoxDeclaration = $rule.Body -match '(?i)\b(?:padding(?:-[a-z]+)?|border(?:-[a-z]+)?|border-radius|background(?:-[a-z]+)?|box-shadow)\s*:'
        foreach ($selector in ($rule.Selector -split ',' | ForEach-Object { $_.Trim() })) {
            $isCodeMirrorLine = $selector -match '(?i)\.CodeMirror-line\b'
            $isWhitelistedMetaPre = $selector -eq '#write pre.md-meta-block'
            $isWritePreDescendant = -not $isWhitelistedMetaPre -and $selector -match '(?i)^#write\b.*(?:\s|[>+~])pre(?:\b|[.:#\[])'
            if (($isCodeMirrorLine -and $hasCodeMirrorLineBoxDeclaration) -or ($isWritePreDescendant -and $hasVisualDeclaration)) {
                return $true
            }
        }
    }
    return $false
}

function Test-HasForbiddenCodeMirrorDeclaration([string]$content) {
    foreach ($rule in (Get-CssRuleBlocks $content)) {
        foreach ($selector in ($rule.Selector -split ',' | ForEach-Object { $_.Trim() })) {
            $isCodeMirrorRule = $selector -match '(?i)(?:\.CodeMirror\b|\.cm-s-(?:inner|typora-default)\b)'
            if (-not $isCodeMirrorRule) { continue }

            $allowsBackground = $selector -match '(?i)(?:\.cm-s-(?:inner|typora-default)|\.CodeMirror-(?:selected|activeline-background|gutters))\s*$'
            $isCursor = $selector -match '(?i)\.CodeMirror-cursor\s*$'
            foreach ($declaration in ([regex]::Matches($rule.Body, '(?im)([a-z-]+)\s*:'))) {
                $property = $declaration.Groups[1].Value.ToLowerInvariant()
                if ($property -in @('color', 'font-family')) { continue }
                if ($property -in @('background', 'background-color') -and $allowsBackground) { continue }
                if ($property -eq 'border-left-color' -and $isCursor) { continue }
                return $true
            }
        }
    }
    return $false
}

